/** Runs a panel action; on failure shows the server's message instead of failing silently. */
async function act(fn: () => Promise<unknown>) {
  try {
    await fn();
  } catch (err) {
    if (err instanceof ApiError && err.status === 401) return showLogin(err.message);
    toast(errText(err));
  }
}
function toast(msg: string) {
  const t = h('div', { class: 'body-5 fixed right-4 bottom-4 left-4 z-50 mx-auto max-w-md rounded-xl bg-red px-4 py-3 text-cream shadow-lg sm:left-auto', role: 'alert' } as Partial<HTMLDivElement>, msg);
  document.body.append(t);
  setTimeout(() => t.remove(), 5000);
}

