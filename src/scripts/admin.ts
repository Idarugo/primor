const TOPIC: Record<string, string> = { personal: 'Consumo personal', negocio: 'Venta a negocio', foodservice: 'Restaurante o FoodService', comuna: 'Comuna' };
let msgFilter: NonNullable<Message['status']> = 'nuevo';
