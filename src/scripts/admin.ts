/* Single series bar chart: one hue, 4px rounded tops, 2px gaps, hover tooltip, table view. */
function renderChart(list: ReturnType<typeof orders.list>) {
  const days = Array.from({ length: 14 }, (_, i) => {
    const d = new Date();
    d.setHours(0, 0, 0, 0);
    d.setDate(d.getDate() - 13 + i);
    return d;
  });
  const data = days.map((d) => {
    const inDay = list.filter((o) => new Date(o.createdAt).toDateString() === d.toDateString());
    return { d, total: inDay.reduce((n, o) => n + o.subtotal, 0), count: inDay.length };
  });
  const box = $('[data-chart]');
  if (!data.some((d) => d.total > 0)) {
    box.replaceChildren(h('div', { class: 'grid size-full place-items-center rounded-xl bg-ink/[0.03] text-center' }, h('div', {}, h('p', { class: 'title-3' }, 'Sin ventas en los últimos 14 días'), h('p', { class: 'caption-5 mt-1 text-ink/50' }, 'Los pedidos aparecerán aquí día a día.'))));
    $('tbody', $('[data-chart-table]')).replaceChildren();
    return;
  }
  const W = 700, H = 220, pad = { l: 48, r: 8, t: 12, b: 24 };
  const maxV = Math.max(1, ...data.map((d) => d.total));
  const step = Math.pow(10, Math.floor(Math.log10(maxV)));
  const top = Math.ceil(maxV / step) * step;
  const bw = (W - pad.l - pad.r) / data.length;
  const y = (v: number) => pad.t + (H - pad.t - pad.b) * (1 - v / top);
  const svgNS = 'http://www.w3.org/2000/svg';
  const svg = document.createElementNS(svgNS, 'svg');
  svg.setAttribute('viewBox', `0 0 ${W} ${H}`);
  svg.setAttribute('class', 'size-full overflow-visible');
  svg.setAttribute('role', 'img');
  svg.setAttribute('aria-label', `Ventas por día, últimos 14 días. Total ${clp(data.reduce((n, d) => n + d.total, 0))}.`);
  const add = (tag: string, attrs: Record<string, string | number>, text?: string) => {
    const n = document.createElementNS(svgNS, tag);
    for (const [k, v] of Object.entries(attrs)) n.setAttribute(k, String(v));
    if (text) n.textContent = text;
    svg.append(n);
    return n;
  };
  [0, 0.5, 1].forEach((f) => {
    const v = top * f;
    add('line', { x1: pad.l, x2: W - pad.r, y1: y(v), y2: y(v), stroke: '#131209', 'stroke-opacity': f === 0 ? 0.25 : 0.08 });
    add('text', { x: pad.l - 8, y: y(v) + 4, 'text-anchor': 'end', 'font-size': 11, fill: '#131209', 'fill-opacity': 0.5 }, v >= 1000 ? `$${Math.round(v / 1000)}k` : `$${v}`);
  });
  const tip = h('div', { class: 'caption-4 pointer-events-none absolute z-10 hidden -translate-x-1/2 -translate-y-full rounded-lg bg-ink px-3 py-2 whitespace-nowrap text-cream shadow-lg' });
  data.forEach((d, i) => {
    const x = pad.l + i * bw + 1;
    const w = bw - 2;
    const hgt = Math.max(0, y(0) - y(d.total));
    if (hgt > 0) {
      const r = Math.min(4, w / 2, hgt);
      const yt = y(d.total);
      add('path', { d: `M${x},${y(0)} V${yt + r} Q${x},${yt} ${x + r},${yt} H${x + w - r} Q${x + w},${yt} ${x + w},${yt + r} V${y(0)} Z`, fill: '#d7261e' });
    }
    if (i % 2 === 1 || data.length <= 7) add('text', { x: x + w / 2, y: H - 6, 'text-anchor': 'middle', 'font-size': 11, fill: '#131209', 'fill-opacity': 0.5 }, String(d.d.getDate()));
    const hit = add('rect', { x: pad.l + i * bw, y: pad.t, width: bw, height: H - pad.t - pad.b, fill: 'transparent', tabindex: 0 });
    const show = () => {
      tip.replaceChildren(h('strong', { class: 'block' }, date(d.d.toISOString(), { weekday: 'short', day: 'numeric', month: 'short' })), `${clp(d.total)} · ${d.count} ${d.count === 1 ? 'pedido' : 'pedidos'}`);
      tip.style.left = `${((pad.l + i * bw + bw / 2) / W) * 100}%`;
      tip.style.top = `${(y(d.total) / H) * 100}%`;
      tip.classList.remove('hidden');
    };
    hit.addEventListener('mouseenter', show);
    hit.addEventListener('focus', show);
    hit.addEventListener('mouseleave', () => tip.classList.add('hidden'));
    hit.addEventListener('blur', () => tip.classList.add('hidden'));
  });
  box.replaceChildren(svg, tip);
  $('tbody', $('[data-chart-table]')).replaceChildren(
    ...data.map((d) => h('tr', { class: 'border-t border-ink/5' }, h('td', { class: 'py-1' }, date(d.d.toISOString(), { weekday: 'short', day: 'numeric', month: 'short' })), h('td', { class: 'py-1 text-right tabular-nums' }, clp(d.total)), h('td', { class: 'py-1 text-right tabular-nums' }, String(d.count)))),
  );
}
