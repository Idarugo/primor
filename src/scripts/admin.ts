type Step = 'setup' | 'password' | 'enroll' | 'totp' | 'change';
function showStep(step: Step) {
  $$<HTMLFormElement>('[data-step]').forEach((f) => (f.hidden = f.dataset.step !== step));
  const f = $<HTMLFormElement>(`[data-step="${step}"]`);
  f.reset();
  f.querySelector<HTMLInputElement>('input')?.focus();
}
const busy = (f: HTMLFormElement, on: boolean) => f.querySelectorAll<HTMLButtonElement>('button[type=submit]').forEach((b) => (b.disabled = on));
function formHandler(step: Step, fn: (d: FormData) => Promise<void>) {
  const f = $<HTMLFormElement>(`[data-step="${step}"]`);
  f.addEventListener('submit', async (e) => {
    e.preventDefault();
    showLoginError('');
    busy(f, true);
    try {
      await fn(new FormData(f));
    } catch (err) {
      showLoginError(errText(err));
    } finally {
      busy(f, false);
    }
  });
}

